import * as XLSX from 'xlsx';

export type Sheet = { name: string; rows: (string | number)[][] };

export function downloadXlsx(filename: string, sheets: Sheet[]) {
  const wb = XLSX.utils.book_new();
  for (const s of sheets) XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(s.rows), s.name.slice(0, 31));
  XLSX.writeFile(wb, filename.endsWith('.xlsx') ? filename : `${filename}.xlsx`);
}

export function downloadCsv(filename: string, rows: (string | number)[][]) {
  const csv = rows.map((r) => r.map((c) => `"${String(c).replace(/"/g, '""')}"`).join(',')).join('\n');
  const a = document.createElement('a');
  a.href = URL.createObjectURL(new Blob([csv], { type: 'text/csv' }));
  a.download = filename.endsWith('.csv') ? filename : `${filename}.csv`;
  a.click();
  URL.revokeObjectURL(a.href);
}

/** "PDF" export: opens a print-ready lab document; the browser's print dialog saves it as PDF. */
export function printPdf(title: string, sheets: Sheet[], intro?: string) {
  const w = window.open('', '_blank');
  if (!w) return;
  const tables = sheets
    .map(
      (s) =>
        `<h2>${s.name}</h2><table>${s.rows
          .map((r, i) => `<tr>${r.map((c) => (i === 0 ? `<th>${c}</th>` : `<td>${c}</td>`)).join('')}</tr>`)
          .join('')}</table>`,
    )
    .join('');
  w.document.write(`<!doctype html><html><head><title>${title}</title><style>
    body{font:12px Inter,system-ui,sans-serif;color:#0E1116;margin:32px;font-variant-numeric:tabular-nums}
    h1{font-size:20px;margin:0 0 4px} h2{font-size:13px;margin:20px 0 6px;letter-spacing:.04em;color:#5A6270}
    table{border-collapse:collapse;width:100%} th,td{border:1px solid #E3E6EB;padding:4px 6px;text-align:left} th{background:#F1F3F6}
    .meta{color:#8A93A3;font-size:11px}
  </style></head><body><h1>${title}</h1><div class="meta">Generated by Helix · ${new Date().toLocaleString()}</div>${intro ? `<p>${intro}</p>` : ''}${tables}<script>setTimeout(()=>print(),300)</script></body></html>`);
  w.document.close();
}
